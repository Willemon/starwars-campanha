const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = vm.createContext({ assert, window: {}, SPECIES_EFFECTS: {}, document: { addEventListener() {} } });
for (const file of ['js/estado.js', 'js/dados/classes.js', 'js/ficha.js']) {
    let text = fs.readFileSync(path.join(__dirname, '../..', file), 'utf8');
    if (file === 'js/estado.js') text = text.split('let syncStatusTimer')[0];
    if (file === 'js/ficha.js') text = text.replace(/renderSheets\(\);\s*$/, '');
    vm.runInContext(text, context);
}
vm.runInContext(`
    const sheet = createEmptySheet(1);
    assert.equal(getForcePointStats(sheet).total, 5);
    assert.equal(prepareForcePoints(sheet), true);
    sheet.forcePoints.current = 2;
    assert.equal(prepareForcePoints(sheet), false, 'Rendering preserves spent points');
    sheet.classes[0].level = 8;
    prepareForcePoints(sheet);
    assert.equal(sheet.forcePoints.current, 9, 'New level renews points');
    assert.equal(getForcePointStats(sheet).dice, 2);
    sheet.talents = ['Forte (Strong in the Force)', 'DADIVA (Force Boon)'];
    prepareForcePoints(sheet);
    assert.equal(sheet.forcePoints.total, 12);
    assert.equal(getForcePointStats(sheet).sides, 8);
    sheet.forcePoints.current = 4;
    const restored = JSON.parse(JSON.stringify(sheet));
    assert.equal(prepareForcePoints(restored), false);
    assert.equal(restored.forcePoints.current, 4, 'Reload preserves resource');
    sheet.classes = [{name:'Jedi',level:14},{name:CLASS_DATA['Jedi Master'].nome,level:1}];
    sheet.forcePoints.className = CLASS_DATA['Jedi Master'].nome;
    assert.equal(getForcePointStats(sheet).total, 17);
    assert.equal(getForcePointStats(sheet).dice, 3);
    sheet.forcePoints.className = 'Jedi';
    assert.equal(getForcePointStats(sheet).total, 15, 'Uses last gained class, not highest base');
    sheet.attributes.DES.mod = 3;
    assert.equal(calculateFlatFootedDefense(sheet), calculateDefense(sheet,'REF') - 3);
    sheet.attributes.DES.mod = -2;
    assert.equal(calculateFlatFootedDefense(sheet), calculateDefense(sheet,'REF'), 'Negative Dexterity still applies');
    sheet.attributes.DES.mod = 3;
    sheet.aptitudes = ['Dodge (Uncanny Dodge I)'];
    assert.equal(calculateFlatFootedDefense(sheet), calculateDefense(sheet,'REF'));
    const legacy = createEmptySheet(2);
    legacy.combat.forcePoints = '0';
    prepareForcePoints(legacy);
    assert.equal(legacy.forcePoints.current, 0, 'Legacy zero is preserved');
    assert.ok(renderForcePoints(sheet).includes('3d8'));
`, context);
console.log('OK: Force Point levels, feats, persistence, multiclass and flat-footed defense.');
